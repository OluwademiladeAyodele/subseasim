"""Valve integrity testing on the dynamic model.

Every test result is calculated from the evolving dynamic state; nothing is
generated by a timer. The test object only (a) verifies isolation, (b)
records the monitored transmitter, (c) applies the acceptance criterion.

pressure_hold  The isolated test volume was pressurised; the monitored
               pressure must not DECAY by more than ``max_change_bar``
               during the hold period.
inflow         The test volume was bled down below the pressure upstream
               of the barrier; the monitored pressure must not RISE by more
               than ``max_change_bar`` (leakage across the closed barrier).
stroke         The valve is commanded to the opposite end position; the
               time from command to end of travel (dead time + travel) is
               compared with the nominal stroke time +- tolerance.

The isolated volume's pressure obeys  C dP/dt = Q_leak + V beta dT/dt  (1),
so the report gives the equivalent leak rate C dP/dt and, separately, the
thermal-expansion contribution V beta dT/dt calculated from the model. The
acceptance limits are ILLUSTRATIVE training values, not a standard.
"""

from __future__ import annotations

import itertools
from dataclasses import dataclass, field
from typing import TYPE_CHECKING, Literal

import numpy as np

from app.core import units as u
from app.simulation.components.elements import RestrictionElement

if TYPE_CHECKING:  # pragma: no cover
    from app.simulation.engine import SimulationEngine

TestType = Literal["pressure_hold", "inflow", "stroke"]
Phase = Literal["stabilising", "holding", "stroking", "passed", "failed", "aborted"]
_ids = itertools.count(1)


class IntegrityTestRejected(ValueError):
    pass


@dataclass
class IntegrityTest:
    id: int
    type: TestType
    name: str
    test_node: str | None
    transmitter: str | None
    valve: str | None
    stabilisation_s: float
    duration_s: float
    max_change_bar: float
    stroke_tolerance_pct: float
    started_s: float
    phase: Phase = "stabilising"
    hold_start_s: float | None = None
    p_hold_start: float | None = None
    p_now: float | None = None
    volume_nodes: list[int] = field(default_factory=list)
    capacitance: float = 0.0
    fluid_volume: float = 0.0
    trace: list[tuple[float, float]] = field(default_factory=list)
    result: dict = field(default_factory=dict)
    message: str = ""
    stroke_target: float | None = None

    def to_dict(self) -> dict:
        return {
            "id": self.id, "type": self.type, "name": self.name, "test_node": self.test_node,
            "transmitter": self.transmitter, "valve": self.valve,
            "stabilisation_s": self.stabilisation_s, "duration_s": self.duration_s,
            "max_change_bar": self.max_change_bar, "stroke_tolerance_pct": self.stroke_tolerance_pct,
            "started_s": self.started_s, "phase": self.phase, "hold_start_s": self.hold_start_s,
            "p_hold_start_pa": self.p_hold_start, "p_now_pa": self.p_now,
            "test_volume_m3": self.fluid_volume, "capacitance_m3_per_bar": self.capacitance * u.PA_PER_BAR,
            "trace": self.trace[-400:], "result": self.result, "message": self.message,
        }


class IntegrityManager:
    def __init__(self, engine: "SimulationEngine"):
        self.e = engine
        self.tests: list[IntegrityTest] = []

    # ------------------------------------------------------------ isolation
    def isolated_volume(self, node: str) -> tuple[list[int], list[str]]:
        """Nodes reachable from ``node`` through valves that are NOT fully
        closed (seat leakage ignored: that is what the test detects), and
        the open path to any boundary found."""
        dyn = self.e.dyn
        net = dyn.net
        start = dyn.layout.node_index[node]
        closed = set()
        for tag, r in self.e.restrictions.items():
            if r.actuator.position_pct <= 0.0 and r.id in dyn.layout.element_link:
                closed.add(dyn.layout.element_link[r.id])
        adj = getattr(net, "_adjacency", None)
        if adj is None:
            adj = [[] for _ in range(net.n)]
            for li in range(net.m):
                a, b = int(net.up[li]), int(net.dn[li])
                adj[a].append((li, b))
                adj[b].append((li, a))
            net._adjacency = adj  # type: ignore[attr-defined]
        seen = {start}
        frontier = [start]
        while frontier:
            i = frontier.pop()
            for li, j in adj[i]:
                if li in closed or j in seen:
                    continue
                seen.add(j)
                frontier.append(j)
        breaches = [net.nodes[i].id for i in seen if net.fixed[i]]
        return sorted(seen), breaches

    def _path_desc(self, breaches: list[str]) -> str:
        names = []
        for b in breaches:
            n = {**self.e.topology.nodes, **self.e.dyn.built.branch_nodes}.get(b)
            names.append(n.name if n else b)
        return ", ".join(names)

    # ----------------------------------------------------------------- start
    def start(self, *, type: TestType, name: str | None = None, test_node: str | None = None, transmitter: str | None = None,
              valve: str | None = None, stabilisation_s: float = 300.0, duration_s: float = 900.0,
              max_change_bar: float = 2.0, stroke_tolerance_pct: float = 20.0) -> IntegrityTest:
        e = self.e
        if e.mode != "dynamic":
            raise IntegrityTestRejected("integrity tests require the dynamic simulation mode")
        if any(t.phase in ("stabilising", "holding", "stroking") for t in self.tests):
            raise IntegrityTestRejected("another integrity test is already running - abort it first")
        t = IntegrityTest(next(_ids), type, name or type.replace("_", " "), test_node, transmitter, valve,
                          stabilisation_s, duration_s, max_change_bar, stroke_tolerance_pct, e.time_s)
        if type == "stroke":
            if valve not in e.restrictions:
                raise IntegrityTestRejected(f"unknown valve {valve!r}")
            r = e.restrictions[valve]
            if r.actuator.is_moving:
                raise IntegrityTestRejected(f"{valve} is already moving")
            target = 0.0 if r.actuator.position_pct >= 50 else 100.0
            t.stroke_target = target
            t.phase = "stroking"
            e.command_valve(valve, "close" if target == 0.0 else "open")
            t.message = f"Stroke test: {valve} commanded {'CLOSE' if target == 0 else 'OPEN'}; timing to end of travel."
        else:
            if transmitter is None or transmitter not in e.readings:
                raise IntegrityTestRejected("a pressure transmitter is required")
            inst = next(i for i in e.instruments if i.tag == transmitter)
            if inst.type != "pressure" or inst.node is None:
                raise IntegrityTestRejected(f"{transmitter} is not a node pressure transmitter")
            node = test_node or inst.node
            t.test_node = node
            vol, breaches = self.isolated_volume(node)
            if breaches:
                raise IntegrityTestRejected(
                    f"isolation NOT verified: the test volume at {node} is open to {self._path_desc(breaches)}. "
                    "Close the bounding valves before starting the test.")
            if inst.node not in [e.dyn.net.nodes[i].id for i in vol]:
                raise IntegrityTestRejected(f"{transmitter} does not measure inside the isolated test volume")
            net = e.dyn.net
            t.volume_nodes = vol
            t.capacitance = float(net.cap_node[vol].sum())
            t.fluid_volume = float(net.vol_node[vol].sum())
            t.message = (f"Isolation verified: {len(vol)} pressure node(s), {t.fluid_volume * 1000:.0f} L, "
                         f"capacitance {t.capacitance * u.PA_PER_BAR * 1000:.3f} L/bar. Stabilising for {stabilisation_s:.0f} s.")
            if stabilisation_s <= 0:
                self._begin_hold(t)
        self.tests.append(t)
        e.events.add(e.time_s, "integrity", f"Integrity test started: {t.name}. {t.message}", component=valve or transmitter)
        return t

    def abort(self, test_id: int, reason: str = "aborted by trainee") -> None:
        for t in self.tests:
            if t.id == test_id and t.phase in ("stabilising", "holding", "stroking"):
                t.phase = "aborted"
                t.message = f"Test aborted: {reason}"
                self.e.events.add(self.e.time_s, "integrity", f"Integrity test {t.name} ABORTED: {reason}", severity="warning")
                return
        raise IntegrityTestRejected(f"no running test with id {test_id}")

    def _begin_hold(self, t: IntegrityTest) -> None:
        p = self.e.dyn.readings()[t.transmitter].value  # type: ignore[index]
        t.phase = "holding"
        t.hold_start_s = self.e.time_s
        t.p_hold_start = p
        t.trace = []
        self._t_start = self.e.dyn.T_node[t.volume_nodes].copy()
        self.e.events.add(self.e.time_s, "integrity",
                          f"{t.name}: hold period started at {u.pa_to_bara(p):.2f} bara ({t.transmitter}); duration {t.duration_s:.0f} s",
                          component=t.transmitter)

    # ---------------------------------------------------------------- update
    def update(self) -> None:
        e = self.e
        for t in self.tests:
            if t.phase == "stroking":
                r = e.restrictions[t.valve]  # type: ignore[index]
                if not r.actuator.is_moving and abs(r.actuator.position_pct - (t.stroke_target or 0)) < 1e-9:
                    measured = e.time_s - t.started_s
                    nominal = r.nominal_stroke_time_s or (r.actuator.delay_s + (r.actuator.close_stroke_time_s if t.stroke_target == 0 and r.actuator.close_stroke_time_s else r.actuator.full_stroke_time_s))
                    dev = 100.0 * (measured - nominal) / nominal
                    ok = abs(dev) <= t.stroke_tolerance_pct
                    t.phase = "passed" if ok else "failed"
                    t.result = {"measured_stroke_time_s": measured, "nominal_stroke_time_s": nominal, "deviation_pct": dev,
                                "tolerance_pct": t.stroke_tolerance_pct, "passed": ok}
                    t.message = (f"Measured stroke time {measured:.1f} s vs nominal {nominal:.1f} s ({dev:+.1f} %, limit "
                                 f"±{t.stroke_tolerance_pct:g} %): {'PASS' if ok else 'FAIL'}.")
                    e.events.add(e.time_s, "integrity", f"Stroke test {t.valve}: {t.message}", component=t.valve,
                                 severity="info" if ok else "warning")
                continue
            if t.phase not in ("stabilising", "holding"):
                continue
            _, breaches = self.isolated_volume(t.test_node)  # type: ignore[arg-type]
            if breaches:
                self.abort(t.id, f"isolation lost - test volume opened to {self._path_desc(breaches)}")
                continue
            rd = e.readings.get(t.transmitter)  # type: ignore[arg-type]
            p = rd.value if rd else None
            t.p_now = p
            if p is not None:
                t.trace.append((e.time_s, u.pa_to_bara(p)))
            if t.phase == "stabilising" and e.time_s - t.started_s >= t.stabilisation_s - 1e-9:
                self._begin_hold(t)
            elif t.phase == "holding" and t.hold_start_s is not None and e.time_s - t.hold_start_s >= t.duration_s - 1e-9:
                self._finish(t)

    def _finish(self, t: IntegrityTest) -> None:
        e = self.e
        p0, p1 = t.p_hold_start, t.p_now
        if p0 is None or p1 is None:
            t.phase = "failed"
            t.message = "No valid pressure reading during the hold - test invalid."
            return
        dp_bar = u.pa_to_bar_delta(p1 - p0)
        dur = e.time_s - (t.hold_start_s or e.time_s)
        rate = (p1 - p0) / dur if dur > 0 else 0.0
        net = e.dyn.net
        dT = float(np.average(e.dyn.T_node[t.volume_nodes] - self._t_start, weights=np.maximum(net.vol_node[t.volume_nodes], 1e-12)))
        thermal_m3 = float((net.vol_node[t.volume_nodes] * net.beta_node[t.volume_nodes]).sum()) * dT
        equiv_leak = t.capacitance * rate  # m3/s, apparent (incl. thermal)
        thermal_rate = thermal_m3 / dur if dur > 0 else 0.0
        if t.type == "pressure_hold":
            change = -dp_bar
            ok = change <= t.max_change_bar
            crit = f"decay {change:.2f} bar (limit {t.max_change_bar:g} bar)"
        else:
            change = dp_bar
            ok = change <= t.max_change_bar
            crit = f"build-up {change:.2f} bar (limit {t.max_change_bar:g} bar)"
        t.phase = "passed" if ok else "failed"
        t.result = {
            "p_start_bara": u.pa_to_bara(p0), "p_end_bara": u.pa_to_bara(p1), "change_bar": dp_bar,
            "rate_bar_per_min": u.pa_to_bar_delta(rate) * 60, "hold_duration_s": dur,
            "apparent_leak_l_per_min": equiv_leak * 1000 * 60,
            "thermal_contribution_l_per_min": thermal_rate * 1000 * 60,
            "net_leak_l_per_min": (equiv_leak - thermal_rate) * 1000 * 60,
            "mean_temperature_change_k": dT, "passed": ok,
        }
        t.message = (f"{'PASS' if ok else 'FAIL'}: {crit}. Apparent volume change C·dP/dt = {equiv_leak * 6e4:+.4f} L/min, "
                     f"of which thermal expansion V·β·dT/dt = {thermal_rate * 6e4:+.4f} L/min (mean ΔT {dT:+.2f} K).")
        e.events.add(e.time_s, "integrity", f"{t.name}: {t.message}", component=t.transmitter, severity="info" if ok else "warning")

    def snapshot(self) -> list[dict]:
        return [t.to_dict() for t in self.tests[-10:]]


def candidate_test_points(engine: "SimulationEngine") -> list[dict]:
    """Pressure transmitters that can monitor a test volume."""
    out = []
    for i in engine.instruments:
        if i.type == "pressure" and i.node is not None:
            out.append({"transmitter": i.tag, "node": i.node, "description": i.description})
    return out


def operable_valves(engine: "SimulationEngine") -> list[str]:
    return [t for t, r in engine.restrictions.items() if isinstance(r, RestrictionElement) and r.available]
